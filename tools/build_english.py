"""Generate the English display cache from the Japanese lessons.

Requires ctranslate2, sentencepiece, beautifulsoup4, tree-sitter and
tree-sitter-javascript. Pass a local CTranslate2 MADLAD-400 model directory.
The model and Python dependencies are only used when rebuilding this file.
Model: Heng666/madlad400-3b-mt-ct2-int8, revision b963b846ca4a5c106b7c64b863802599993e5f3b.
"""
import argparse
import json
from pathlib import Path
import re

from bs4 import BeautifulSoup, Comment
import ctranslate2
import sentencepiece
from tree_sitter import Language, Parser
import tree_sitter_javascript


ROOT = Path(__file__).resolve().parents[1]
JP = re.compile(r"[ぁ-ゖァ-ヺ一-龯々]")
ATTRS = ("title", "aria-label", "alt", "placeholder")
PARSER = Parser(Language(tree_sitter_javascript.language()))


def phrases():
    result = set()

    def add(value):
        for line in value.splitlines():
            text = line.strip()
            if JP.search(text):
                result.add(text)

    def markup(source):
        doc = BeautifulSoup(source, "html.parser")
        for tag in doc.find_all(["style", "script"]):
            tag.decompose()
        for tag in doc.find_all(True):
            for attr in ATTRS:
                add(tag.get(attr, ""))
            if tag.name == "p" and tag.find(["b","strong","em","kbd"]):
                add(tag.get_text())
        for node in doc.find_all(string=True):
            if not isinstance(node, Comment):
                add(str(node))

    for path in [ROOT / "index.html", *sorted((ROOT / "apps").glob("*.html"))]:
        source = path.read_text(encoding="utf-8")
        markup(source)
        for code in re.findall(r"<script\b[^>]*>(.*?)</script>", source, re.S | re.I):
            stack = [PARSER.parse(code.encode()).root_node]
            while stack:
                node = stack.pop()
                if node.type != "string_fragment":
                    stack.extend(node.named_children)
                    continue
                value = node.text.decode()
                if not JP.search(value):
                    continue
                # Template interpolations may split a tag; extract the remaining
                # visible text, leaving CSS, element names and attributes alone.
                value = re.sub(r'^[^<>\n]*?">', '', value)
                if "<" in value or ">" in value:
                    markup(value)
                    if re.search(r"<(?:b|strong|em|kbd)>",value) and not re.search(r"<(?:svg|button|input|div|li|p)\b",value):
                        add(BeautifulSoup(value,"html.parser").get_text())
                else:
                    for piece in value.split("|"):
                        add(piece)
    return sorted(result)


def build(model):
    tokenizer = sentencepiece.SentencePieceProcessor(model_file=str(model / "spiece.model"))
    engine = ctranslate2.Translator(str(model), compute_type="int8", inter_threads=2, intra_threads=8)
    output = ROOT / "assets" / "english-cache.js"
    existing = {}
    if output.exists():
        content = output.read_text(encoding="utf-8")
        existing = json.loads(content[content.index("{"):content.rindex("}")+1])
    reviewed = json.loads((ROOT / "tools" / "english-reviewed.json").read_text(encoding="utf-8"))
    existing.update(reviewed)
    # The translation model expects a sentence. Feeding an entire explanation
    # at once can drop a subsequent condition or terminal designation.
    lines = {key: re.findall(r"[^。！？]+[。！？]*|[。！？]+",key) for key in phrases()}
    strings = sorted({s for parts in lines.values() for s in parts if s not in existing and JP.search(s)}, key=len)
    jobs = []
    for start in range(0, len(strings), 16):
        batch = strings[start:start + 16]
        tokens = [tokenizer.encode("<2en> "+s, out_type=str) + ["</s>"] for s in batch]
        jobs.extend(engine.translate_batch(tokens, asynchronous=True, beam_size=1, max_decoding_length=180,
                                           no_repeat_ngram_size=4))
    existing.update({key: tokenizer.decode(job.result().hypotheses[0]).strip() for key, job in zip(strings, jobs)})
    cache = {key: reviewed.get(key) or " ".join(existing.get(s,s) for s in parts) for key,parts in lines.items()}
    output.parent.mkdir(exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/build_english.py from the Japanese lesson text.\n")
        f.write("window.lessonEnglish = ")
        json.dump(cache, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write(";\n")
    print(f"Translated {len(cache)} lesson strings.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path)
    build(parser.parse_args().model)
